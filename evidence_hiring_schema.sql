-- EvidenceHire: целевая схема для изолированной оценки кандидатов.
-- Скрипт идемпотентен и не удаляет старые таблицы или результаты проекта.
create extension if not exists pgcrypto;

create table if not exists public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 160),
  retention_days integer not null default 365 check (retention_days between 30 and 3650),
  created_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','admin','interviewer','viewer')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create table if not exists public.job_profiles (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  slug text not null,
  name text not null,
  family text not null default 'Другое',
  version integer not null default 1 check (version > 0),
  status text not null default 'draft' check (status in ('draft','expert_reviewed','pilot','validated','archived')),
  definition jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, slug, version)
);

create table if not exists public.candidates (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  full_name text not null check (char_length(full_name) between 1 and 200),
  email text,
  consent_at timestamptz,
  retention_until date,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.assessments (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  candidate_id uuid not null references public.candidates(id) on delete cascade,
  job_profile_id uuid references public.job_profiles(id) on delete set null,
  profile_key text not null,
  status text not null default 'assessment' check (status in ('assessment','decision','closed')),
  final_decision text check (final_decision is null or final_decision in ('next','offer','reserve','decline')),
  decision_reason text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.assessment_evidence (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  assessment_id uuid not null references public.assessments(id) on delete cascade,
  rater_id uuid not null references auth.users(id) on delete cascade,
  method text not null check (method in ('structured_interview','work_sample','eligibility','other')),
  item_id text not null,
  rating numeric(4,2) check (rating is null or rating between 1 and 5),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (assessment_id, rater_id, method, item_id)
);

create table if not exists public.assessment_invites (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  assessment_id uuid not null references public.assessments(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null default (now() + interval '7 days'),
  candidate_response text,
  consent_at timestamptz,
  submitted_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.outcome_followups (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  assessment_id uuid not null references public.assessments(id) on delete cascade,
  checkpoint_days integer not null check (checkpoint_days in (30,60,90)),
  retained boolean,
  manager_rating numeric(4,2) check (manager_rating is null or manager_rating between 1 and 5),
  kpi_value numeric,
  kpi_definition text,
  notes text,
  recorded_by uuid references auth.users(id) on delete set null,
  recorded_at timestamptz not null default now(),
  unique (assessment_id, checkpoint_days)
);

create table if not exists public.hiring_audit_log (
  id bigint generated by default as identity primary key,
  organization_id uuid references public.organizations(id) on delete set null,
  actor_id uuid references auth.users(id) on delete set null,
  entity_type text not null,
  entity_id text,
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists candidates_org_created_idx on public.candidates(organization_id, created_at desc);
create index if not exists assessments_org_created_idx on public.assessments(organization_id, created_at desc);
create index if not exists evidence_assessment_idx on public.assessment_evidence(assessment_id);
create index if not exists invites_assessment_idx on public.assessment_invites(assessment_id);
create index if not exists outcomes_assessment_idx on public.outcome_followups(assessment_id);

create or replace function public.is_org_member(target_org uuid)
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.organization_members m where m.organization_id = target_org and m.user_id = auth.uid()) $$;
revoke all on function public.is_org_member(uuid) from public, anon;
grant execute on function public.is_org_member(uuid) to authenticated;

create or replace function public.has_org_role(target_org uuid, accepted_roles text[])
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.organization_members m where m.organization_id = target_org and m.user_id = auth.uid() and m.role = any(accepted_roles)) $$;
revoke all on function public.has_org_role(uuid,text[]) from public, anon;
grant execute on function public.has_org_role(uuid,text[]) to authenticated;

