create or replace function public.create_assessment_invite(target_assessment uuid)
returns text language plpgsql security definer set search_path = public
as $$
declare raw_token text := encode(gen_random_bytes(32),'hex'); target_org uuid;
begin
  select organization_id into target_org from public.assessments where id = target_assessment;
  if target_org is null or not public.has_org_role(target_org,array['owner','admin']) then raise exception 'not authorized'; end if;
  insert into public.assessment_invites(organization_id,assessment_id,token_hash,created_by)
  values(target_org,target_assessment,encode(digest(raw_token,'sha256'),'hex'),auth.uid());
  return raw_token;
end $$;
revoke all on function public.create_assessment_invite(uuid) from public, anon;
grant execute on function public.create_assessment_invite(uuid) to authenticated;

create or replace function public.get_candidate_assignment(raw_token text)
returns table(assessment_id uuid,candidate_name text,profile_key text,profile_definition jsonb,candidate_response text,submitted_at timestamptz,expires_at timestamptz)
language sql stable security definer set search_path = public
as $$
  select a.id,c.full_name,a.profile_key,coalesce(j.definition,'null'::jsonb),i.candidate_response,i.submitted_at,i.expires_at
  from public.assessment_invites i join public.assessments a on a.id=i.assessment_id join public.candidates c on c.id=a.candidate_id
  left join public.job_profiles j on j.id=a.job_profile_id
  where i.token_hash=encode(digest(raw_token,'sha256'),'hex') and i.expires_at>now()
  limit 1
$$;
revoke all on function public.get_candidate_assignment(text) from public, authenticated;
grant execute on function public.get_candidate_assignment(text) to anon;

create or replace function public.submit_candidate_assignment(raw_token text,response_text text,consent_given boolean)
returns boolean language plpgsql security definer set search_path = public
as $$
declare changed integer;
begin
  if consent_given is not true or char_length(trim(response_text)) < 20 or char_length(response_text) > 20000 then return false; end if;
  update public.assessment_invites set candidate_response=response_text,consent_at=now(),submitted_at=now()
  where token_hash=encode(digest(raw_token,'sha256'),'hex') and expires_at>now() and submitted_at is null;
  get diagnostics changed = row_count;
  return changed=1;
end $$;
revoke all on function public.submit_candidate_assignment(text,text,boolean) from public, authenticated;
grant execute on function public.submit_candidate_assignment(text,text,boolean) to anon;

create or replace function public.purge_expired_candidates()
returns integer language plpgsql security definer set search_path = public
as $$ declare removed integer; begin
  delete from public.candidates where retention_until is not null and retention_until < current_date;
  get diagnostics removed = row_count;
  return removed;
end $$;
revoke all on function public.purge_expired_candidates() from public, anon, authenticated;
