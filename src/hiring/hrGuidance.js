const STANDARD_PROBES = [
  "Что в этой ситуации сделали лично вы, а что — другие участники?",
  "Какой ранний сигнал риска вы заметили и когда сообщили о нём?",
  "Какой результат, срок или запись может подтвердить ваш ответ?",
];

export function buildVerificationGuidance(profile, result) {
  const items = [
    ...profile.workSample.rubric.map((item) => ({ ...item, label: item.criterion, method: "рабочая проба" })),
    ...profile.interview.map((item) => ({ ...item, label: item.text, method: "интервью" })),
  ];
  const ratings = new Map(result.evidence.map((item) => [`${item.method}:${item.id}`, item.score]));
  const missing = items.filter((item) => !ratings.has(`${item.method === "рабочая проба" ? "work_sample" : "structured_interview"}:${item.id}`));
  const weak = items.filter((item) => {
    const key = `${item.method === "рабочая проба" ? "work_sample" : "structured_interview"}:${item.id}`;
    const score = ratings.get(key);
    return score != null && score <= 2;
  });

  return {
    missing: missing.slice(0, 3).map((item) => `${item.method}: ${item.label}`),
    weak: weak.slice(0, 3).map((item) => `${item.label} — ${item.anchors?.[1] || "нужно перепроверить наблюдаемыми фактами"}`),
    scenario: ROLE_PLAY_SCENARIOS[profile.id] || "Дайте кандидату новый короткий рабочий эпизод по самому слабому критерию и оцените его той же поведенческой шкалой.",
    probes: STANDARD_PROBES,
  };
}
